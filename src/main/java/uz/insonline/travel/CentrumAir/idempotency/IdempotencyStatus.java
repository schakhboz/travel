package uz.insonline.travel.CentrumAir.idempotency;

/** Состояние заявки на выпуск (ТЗ п. 7.2–7.3). */
public enum IdempotencyStatus {

    /** Заявка принята, выпуск идёт. */
    IN_PROGRESS,

    /** Часть полисов заявки выпущена, остальные — нет: повтор довыпустит недостающие. */
    PARTIAL,

    /** Все полисы заявки выпущены, ответ сохранён для повторов. */
    COMPLETED,

    /** Выпуск завершился ошибкой; повтор с тем же ключом продолжит с недостающих полисов. */
    FAILED
}
